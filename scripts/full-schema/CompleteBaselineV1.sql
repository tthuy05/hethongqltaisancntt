    asset_type_id bigint,
    minimum_age_months integer,
    maximum_maintenance_cost_ratio numeric(5,4),
    minimum_maintenance_count integer,
    require_warranty_expired boolean NOT NULL DEFAULT FALSE,
    minimum_failure_count integer,
    estimated_unit_cost numeric(18,2),
    priority integer NOT NULL DEFAULT 100,
    effective_from_utc timestamp with time zone NOT NULL DEFAULT (clock_timestamp()),
    effective_to_utc timestamp with time zone,
    is_active boolean NOT NULL DEFAULT TRUE,
    description character varying(2000),
    created_at_utc timestamp with time zone NOT NULL DEFAULT (clock_timestamp()),
    updated_at_utc timestamp with time zone,
    row_version bytea NOT NULL,
    CONSTRAINT pk_replacement_rules PRIMARY KEY (id),
    CONSTRAINT ck_replacement_rules_at_least_one_condition CHECK (minimum_age_months IS NOT NULL OR maximum_maintenance_cost_ratio IS NOT NULL OR minimum_maintenance_count IS NOT NULL OR require_warranty_expired OR minimum_failure_count IS NOT NULL),
    CONSTRAINT ck_replacement_rules_effective_period CHECK (effective_to_utc IS NULL OR effective_to_utc > effective_from_utc),
    CONSTRAINT ck_replacement_rules_estimated_unit_cost_nonnegative CHECK (estimated_unit_cost IS NULL OR (estimated_unit_cost >= 0 AND estimated_unit_cost <> 'NaN'::numeric)),
    CONSTRAINT ck_replacement_rules_minimum_age_months_positive CHECK (minimum_age_months IS NULL OR minimum_age_months > 0),
    CONSTRAINT ck_replacement_rules_minimum_failure_count_positive CHECK (minimum_failure_count IS NULL OR minimum_failure_count > 0),
    CONSTRAINT ck_replacement_rules_minimum_maintenance_count_positive CHECK (minimum_maintenance_count IS NULL OR minimum_maintenance_count > 0),
    CONSTRAINT ck_replacement_rules_priority_nonnegative CHECK (priority >= 0),
    CONSTRAINT ck_replacement_rules_ratio CHECK (maximum_maintenance_cost_ratio IS NULL OR maximum_maintenance_cost_ratio BETWEEN 0 AND 1),
    CONSTRAINT ck_replacement_rules_row_version_length CHECK (octet_length(row_version) = 16),
    CONSTRAINT ck_replacement_rules_version_positive CHECK (version > 0),
    CONSTRAINT fk_replacement_rules_asset_type_id FOREIGN KEY (asset_type_id) REFERENCES public.asset_types (id)
);

