    CONSTRAINT ck_maintenance_histories_cost_nonnegative CHECK (cost IS NULL OR (cost >= 0 AND cost <> 'NaN'::numeric)),
    CONSTRAINT ck_maintenance_histories_event_type CHECK (event_type IN ('CREATED','STATUS_CHANGED','ASSIGNED','COMMENTED','COST_UPDATED','RESOLVED','FAILED','CANCELLED')),
    CONSTRAINT ck_maintenance_histories_from_status CHECK (from_status IN ('PENDING','IN_PROGRESS','RESOLVED','FAILED','CANCELLED')),
    CONSTRAINT ck_maintenance_histories_to_status CHECK (to_status IN ('PENDING','IN_PROGRESS','RESOLVED','FAILED','CANCELLED')),
